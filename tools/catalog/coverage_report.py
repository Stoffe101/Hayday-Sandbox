#!/usr/bin/env python3
"""Honest catalogue coverage report -> docs/CATALOG_COVERAGE.md

Counts per category how many items have: trustworthy footprints, unknown
(provisional) footprints, unlock levels, prices, dedicated placeholder art,
shared generic placeholder art, or no art. Placeholder records never count as
"verified". Usage: python3 tools/catalog/coverage_report.py [--stdout]
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    cats = json.loads((ROOT / "data/items/categories.json").read_text())["categories"]
    names = {c["id"]: c["name"] for c in cats}
    order = {c["id"]: c["order"] for c in cats}
    pack = json.loads((ROOT / "assets/placeholders/pack.json").read_text())["sprites"]
    rows: dict[str, Counter] = defaultdict(Counter)
    total = Counter()
    for f in sorted((ROOT / "data/items").glob("*.json")):
        if f.name == "categories.json":
            continue
        for it in json.loads(f.read_text(encoding="utf-8"))["items"]:
            c = rows[it["category"]]
            st = it.get("footprint_status", "unknown" if it.get("footprint") is None else "unverified")
            c["items"] += 1
            c["fp_" + st] += 1
            if it.get("unlock_level") is not None:
                c["level"] += 1
            cost = it.get("cost") or {}
            if cost.get("coins") is not None or cost.get("diamonds") is not None:
                c["cost"] += 1
            e = pack.get(it.get("art", it["id"]))
            if not e:
                c["art_none"] += 1
            elif e.get("shared"):
                c["art_shared"] += 1
            else:
                c["art_own"] += 1
            if not it.get("placeable", True):
                c["reference_only"] += 1
    for c in rows.values():
        total.update(c)
    lines = [
        "# Catalogue coverage",
        "",
        "Generated by `tools/catalog/coverage_report.py` from `data/items/*.json` and the built-in placeholder pack.",
        "Footprint columns: **trusted** = confirmed or community-sourced (wiki data); **weak** = approximation/unverified;",
        "**unknown** = no source, provisional planning size only. Art: **own** = a placeholder generated for that",
        "specific item; **shared** = generic placeholder shared by items of the same kind/colour/size. All art is",
        "original placeholder art — no item has official artwork.",
        "",
        "| Category | Items | Footprint trusted | weak | unknown | Unlock level | Price | Art own | Art shared | No art | Reference only |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]

    def row(label: str, c: Counter) -> str:
        trusted = c["fp_confirmed"] + c["fp_community"] + c["fp_original"]
        weak = c["fp_approximation"] + c["fp_unverified"]
        return f"| {label} | {c['items']} | {trusted} | {weak} | {c['fp_unknown']} | {c['level']} | {c['cost']} | {c['art_own']} | {c['art_shared']} | {c['art_none']} | {c['reference_only']} |"

    for cid in sorted(rows, key=lambda k: order.get(k, 99)):
        lines.append(row(names.get(cid, cid), rows[cid]))
    lines.append(row("**Total**", total))
    lines += [
        "",
        f"Of {total['items']} records, {total['fp_confirmed']} have footprints marked *confirmed* (cross-checked wiki infoboxes),",
        f"{total['fp_community']} *community* (single fan-wiki source), {total['fp_unknown']} have no known footprint.",
        "Unlock levels for most decorations are a wiki default of 1, not a verified gate (see docs/research/ITEM_DATA_RESEARCH.md).",
        "",
    ]
    text = "\n".join(lines)
    if "--stdout" in sys.argv:
        print(text)
    else:
        (ROOT / "docs/CATALOG_COVERAGE.md").write_text(text, encoding="utf-8")
        print(lines[-4])
    return 0


if __name__ == "__main__":
    sys.exit(main())
